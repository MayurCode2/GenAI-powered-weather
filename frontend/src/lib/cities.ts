export type CityOption = (typeof CITY_OPTIONS)[number];

export function filterCities(query: string, limit = 12): string[] {
  const q = query.trim().toLowerCase();
  if (!q) return [...CITY_OPTIONS].slice(0, limit);
  return CITY_OPTIONS.filter((c) => c.toLowerCase().includes(q)).slice(0, limit);
}
